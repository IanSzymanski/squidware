import { createRequire } from 'node:module';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createQa, root } from './testing/launcher.mjs';
const qa = await createQa('shared-routes', { timeoutMs: 180000 });
const fixture = path.join(qa.output, 'routes.squid');
await fs.copyFile(path.join(root, 'format/examples/basic-v2.squid'), fixture);
const require = createRequire(import.meta.url);
const esbuild = require(require.resolve('esbuild', { paths: [path.dirname(require.resolve('vite/package.json'))] }));
const bundle = path.join(qa.output, 'geometry.cjs');
await esbuild.build({ stdin: { contents: `export {fitSharedRoute} from './src/editor/routeEditing'; export {compileRoute} from './src/sharedRoutes';`, resolveDir: root, loader: 'ts' }, bundle: true, platform: 'node', format: 'cjs', outfile: bundle, logLevel: 'silent' });
await qa.run('shared-routes-qa-runner.cjs', 'route-manifest', { fixture, bundle });
