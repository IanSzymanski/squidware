import { readFile, readdir, realpath, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const noticesPath = join(root, 'THIRD_PARTY_NOTICES.txt');
const normalized = (text) => text.replace(/\r\n/g, '\n').trim();

async function readPackage(directory) {
  return JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
}

// Walk node_modules ancestors so this works with both pnpm's linked store and
// conventional nested/hoisted installs, without depending on package exports.
async function locatePackage(name, from) {
  let directory = await realpath(from);
  while (true) {
    const candidate = join(directory, 'node_modules', name);
    try {
      const actual = await realpath(candidate);
      if ((await readPackage(actual)).name === name) return actual;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    const parent = dirname(directory);
    if (parent === directory) throw new Error(`Cannot find installed dependency ${name} from ${from}`);
    directory = parent;
  }
}

export async function generateNotices() {
  const manifest = await readPackage(root);
  const packages = new Map();

  async function visit(name, from) {
    const directory = await locatePackage(name, from);
    const pkg = await readPackage(directory);
    const key = `${pkg.name}@${pkg.version}`;
    if (packages.has(key)) return;
    packages.set(key, { directory, pkg });
    for (const child of Object.keys(pkg.dependencies ?? {}).sort()) await visit(child, directory);
    for (const child of Object.keys(pkg.optionalDependencies ?? {}).sort()) {
      try {
        await locatePackage(child, directory);
      } catch (error) {
        if (error.message.startsWith('Cannot find installed dependency')) continue;
        throw error;
      }
      await visit(child, directory);
    }
  }

  for (const name of Object.keys(manifest.dependencies ?? {}).sort()) await visit(name, root);
  // Electron is a build dependency, but its binary is the shipped application runtime.
  const electronDirectory = await locatePackage('electron', root);
  const electron = await readPackage(electronDirectory);
  packages.set(`electron@${electron.version}`, { directory: electronDirectory, pkg: electron });

  const blocks = [
    'Squidware third-party notices',
    'Generated by scripts/generate-notices.mjs from the installed, locked runtime dependencies.\n'
      + 'These components retain their own licenses; Squidware\'s MIT license does not replace them.\n'
      + 'Build/test-only tools are not included in this application runtime inventory.\n'
      + 'Electron\'s complete Chromium/runtime notices are distributed separately as\n'
      + 'resources/legal/LICENSES.chromium.html (Contents/Resources/legal on macOS).\n'
      + 'See docs/licensing.md for update and redistribution instructions.',
  ];

  for (const key of [...packages.keys()].sort()) {
    const { directory, pkg } = packages.get(key);
    const files = (await readdir(directory, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && /^(licen[cs]e|notice|copying)(?:[.-].*)?$/i.test(entry.name))
      .map((entry) => entry.name).sort();
    if (!files.length) throw new Error(`No license/notice file found for ${key}; review its distribution terms.`);
    const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type;
    if (!license) throw new Error(`No license metadata found for ${key}; review its distribution terms.`);
    blocks.push(`${'='.repeat(72)}\n${key}\nDeclared license: ${license}`);
    for (const file of files) blocks.push(`--- ${file} ---\n${normalized(await readFile(join(directory, file), 'utf8'))}`);
    if (pkg.name === 'lucide-react') {
      // Lucide's ISC notice identifies inherited Feather icons as MIT licensed.
      blocks.push('--- Feather portions (MIT) ---\n'
        + 'Upstream: https://github.com/feathericons/feather/blob/v4.29.2/LICENSE\n'
        + normalized(await readFile(join(root, 'licenses/Feather-LICENSE.txt'), 'utf8')));
    }
  }
  return `${blocks.join('\n\n')}\n`;
}

export async function checkNotices() {
  const expected = await generateNotices();
  const actual = await readFile(noticesPath, 'utf8').catch((error) => {
    if (error.code === 'ENOENT') return '';
    throw error;
  });
  if (normalized(actual) !== normalized(expected)) {
    throw new Error('THIRD_PARTY_NOTICES.txt is missing or stale. Run pnpm licenses:generate, review the changes, and commit the notices.');
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  if (process.argv.includes('--check')) {
    await checkNotices();
    console.log('Runtime dependency notices are current.');
  } else {
    await writeFile(noticesPath, await generateNotices(), 'utf8');
    console.log('Updated THIRD_PARTY_NOTICES.txt. Review dependency license changes before redistribution.');
  }
}
