import { promises as fs } from 'node:fs';
import path from 'node:path';
import { createQa } from './testing/launcher.mjs';
const qa = await createQa('metronome', { timeoutMs: 240000 });
const rate = 8000, seconds = 60, wav = Buffer.alloc(44 + rate * seconds * 2);
wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8,4); wav.write('WAVEfmt ',8);
wav.writeUInt32LE(16,16); wav.writeUInt16LE(1,20); wav.writeUInt16LE(1,22);
wav.writeUInt32LE(rate,24); wav.writeUInt32LE(rate*2,28); wav.writeUInt16LE(2,32); wav.writeUInt16LE(16,34);
wav.write('data',36); wav.writeUInt32LE(wav.length-44,40);
const recording = path.join(qa.output,'rehearsal.wav'); await fs.writeFile(recording,wav);
await qa.run('metronome-qa-runner.cjs', 'metronome-manifest', { recording });
